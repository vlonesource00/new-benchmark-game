// Headless endurance race on the game engine fork.
//   node scripts/sim-endurance.mjs --calibrate            measure unscaled fuel/wear per metre
//   node scripts/sim-endurance.mjs --laps 6 --teams 6 --seed 7 [--track harbor-ring] [--difficulty 0.9]
//   node scripts/sim-endurance.mjs --profile [--track harbor-ring]   record the difficulty reference pace
import { Track } from '../game/engine/sim/track.js';
import { EnduranceRace, FIXED_DT, maxWear } from '../game/core/race.js';
import { FORMATS, COMPOUNDS } from '../game/core/rules.js';
import { drawTeams, AI_DRIVERS, mulberry32 } from '../game/core/teams.js';
import { assignClasses, gridFromQualifying } from '../game/core/classes.js';

const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : fallback; };
const trackName = opt('track', 'harbor-ring');
const fmt = (t) => t == null ? '—' : `${Math.floor(t / 60)}:${(t % 60).toFixed(3).padStart(6, '0')}`;

if (args.includes('--calibrate')) {
  const track = new Track(trackName);
  const teams = [{ id: 'cal', name: 'CAL', short: 'CAL', color: '#fff', index: 0, starter: 0, drivers: [{ kind: 'ai', id: 'astra', name: 'ASTRA', short: 'AST' }], grid: 0 }];
  const race = new EnduranceRace({ track, teams, format: { ...FORMATS.custom, mandatoryStops: 0, mandatorySwap: false }, laps: 30 });
  race.cal.fuelScale = 1; race.cal.wearScale = 1; race.start();
  const car = race.cars[0]; let mark = null; const samples = [];
  while (car.race.lap <= 4 && race.time < 900) {
    race.step(FIXED_DT);
    if (car.race.lap >= 2 && (!mark || car.race.lap !== mark.lap)) {
      if (mark) samples.push({ fuel: mark.fuel - car.fuel, wear: maxWear(car) - mark.wear, m: car.race.progress - mark.progress, lapTime: car.race.lastLap });
      mark = { lap: car.race.lap, fuel: car.fuel, wear: maxWear(car), progress: car.race.progress };
    }
  }
  const tot = samples.reduce((a, s) => ({ fuel: a.fuel + s.fuel, wear: a.wear + s.wear, m: a.m + s.m }), { fuel: 0, wear: 0, m: 0 });
  console.log(JSON.stringify({ track: trackName, length: track.length, laps: samples.map((s) => fmt(s.lapTime)), fuelPerM: tot.fuel / tot.m, wearPerM: tot.wear / tot.m }, null, 1));
  process.exit(0);
}

if (args.includes('--profile')) {
  // Reference pace for the difficulty governor: each track-ready AI runs solo,
  // the fastest clean lap (lap 2 or 3) is binned by track distance and written
  // to game/core/pace-profiles.js.
  const { writeFileSync } = await import('node:fs');
  const { PACE_PROFILES } = await import('../game/core/pace-profiles.js');
  const track = new Track(trackName), BIN = 5, n = Math.ceil(track.length / BIN);
  let best = null;
  for (const d of AI_DRIVERS.filter((x) => x.anyTrack || trackName === 'harbor-ring')) {
    const teams = [{ id: 'p', name: 'P', short: 'P', color: '#fff', index: 0, starter: 0, drivers: [{ kind: 'ai', id: d.id, name: d.name, short: d.short }], grid: 0 }];
    const race = new EnduranceRace({ track, teams, format: { ...FORMATS.custom, mandatoryStops: 0, mandatorySwap: false }, laps: 30 });
    race.start();
    const car = race.cars[0]; let bins = null, lap = 0;
    while (car.race.lap <= 3 && race.time < 600) {
      race.step(FIXED_DT);
      if (car.race.lap !== lap) {
        if (bins && car.race.lastLap && (!best || car.race.lastLap < best.time) && bins.every((b) => b > 0)) best = { time: car.race.lastLap, v: bins, who: d.name };
        lap = car.race.lap; bins = lap >= 2 ? new Array(n).fill(0) : null;
      }
      if (bins) { const i = Math.floor(track.nearest(car.x, car.z).s / BIN) % n; bins[i] = Math.max(bins[i], car.speed); }
    }
    console.log(`  ${d.name.padEnd(12)} best ${fmt(car.race.bestLap)}`);
  }
  if (!best) { console.error('no clean lap'); process.exit(1); }
  PACE_PROFILES[track.id] = { bin: BIN, lap: +best.time.toFixed(3), by: best.who, v: best.v.map((x) => +x.toFixed(2)) };
  const body = Object.entries(PACE_PROFILES).map(([k, p]) => `  '${k}': { bin: ${p.bin}, lap: ${p.lap}, by: '${p.by}',
    v: [${p.v.join(',')}] }`).join(',\n');
  writeFileSync(new URL('../game/core/pace-profiles.js', import.meta.url), `// Reference speed profiles for the difficulty governor. Generated by
// node scripts/sim-endurance.mjs --profile --track <id>
export const PACE_PROFILES = {
${body}
};
`);
  console.log(`${track.id}: ${best.who} ${fmt(best.time)} · ${n} bins`);
  process.exit(0);
}

const laps = Number(opt('laps', 6)), teamCount = Number(opt('teams', 6)), seed = Number(opt('seed', 7));
const track = new Track(trackName);
const ready = (d) => d.anyTrack || trackName === 'harbor-ring';
let teams = assignClasses(drawTeams({ teamCount, seed, trackReady: ready }), opt('field', 'gt3'), 'gt3', mulberry32(seed));
const difficultyK = Number(opt('difficulty', 1));
if (args.includes('--quali')) {
  // Lone qualifying first; its classification sets the race grid.
  const q = new EnduranceRace({ track, teams, format: FORMATS.custom, laps: 2, difficulty: difficultyK, session: 'qualifying' });
  q.start(); const qw = Date.now();
  while (q.phase !== 'finished') q.step(FIXED_DT);
  const res = q.classification();
  console.log(`qualifying ${fmt(q.time)} in ${((Date.now() - qw) / 1000).toFixed(1)}s wall · contacts ${q.contacts}`);
  for (const r of res) console.log(`  Q${r.position} ${r.raceClass.toUpperCase()} P${r.classPosition} ${teams.find((t) => t.id === r.team).short} best ${fmt(r.bestLap)} inc ${r.incidents}x`);
  teams = gridFromQualifying(teams, res);
}
const format = Object.values(FORMATS).find((f) => f.laps === laps) ?? FORMATS.custom;
const difficulty = Number(opt('difficulty', 1));
const race = new EnduranceRace({ track, teams, format, laps, difficulty });
console.log(`${trackName} · ${race.laps} laps · fuel stint ${race.cal.fuelLaps} laps · tyre life ${race.cal.tyreLaps} laps (medium)`);
for (const t of teams) console.log(`  P${t.grid + 1} ${t.name.padEnd(20)} ${t.drivers.map((d, i) => (i === t.starter ? '*' : ' ') + d.name).join('  ')}`);
race.start();
const wall = Date.now(); let seen = 0;
const limit = race.laps * 200 + 300;
while (race.phase !== 'finished' && race.time < limit) {
  race.step(FIXED_DT);
  while (seen < race.eventSeq) { const e = race.events.find((x) => x.id === seen + 1); seen++; if (e) console.log(`  [${fmt(e.time)}] ${e.type.toUpperCase().padEnd(8)} ${e.text}`); }
}
console.log(`\nsim ${fmt(race.time)} in ${((Date.now() - wall) / 1000).toFixed(1)}s wall · contacts ${race.contacts} · phase ${race.phase}`);
const order = race.standings();
order.forEach((c, i) => {
  const e = race.entryOf(c);
  console.log(`P${i + 1} ${(e.team.raceClass ?? 'gt3').toUpperCase()} ${e.team.short} ${fmt(c.race.finishTime).padStart(9)} best ${fmt(c.race.bestLap)} stops ${e.strategist.stops} swaps ${e.strategist.swaps} fuel ${c.fuel.toFixed(1)}L wear ${(maxWear(c) * 100).toFixed(0)}% ${COMPOUNDS[c.wheels[0].tyre.compound].short} lap ${c.race.lap - 1} · inc ${race.stewards.of(e).inc}x${c.race.dq ? ' DQ' : ''} dmg ${((c.damage ?? 0) * 100).toFixed(0)}% · stints ${e.stints.map((s) => `${e.team.drivers[s.driver].short}${s.fromLap}-${s.toLap ?? '?'}`).join(' ')}`);
});
void AI_DRIVERS;
