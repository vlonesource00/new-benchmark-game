import { Track } from "../src/sim/track.js";
import { Session } from "../src/sim/session.js";
import { observeVehicle } from "../src/sim/native-adapter.js";
const track = new Track("harbor-ring");
const session = new Session(track, { classId: "gt" });
session.mode = "practice";
session.autopilot = true;
session.start();
const car = session.cars[0];
const dt = 1/120;
for (let step = 0; step < 481; step++) session.step(dt, { throttle: 0, brake: 0, steer: 0 });
const ai = session.drivers[0].ai;
const obs = observeVehicle(car, [car], { time: session.time }, dt);
const cmd = ai.step(obs);
console.log("command", cmd);
console.log("ai state", JSON.stringify(ai.state, (k, v) => (typeof v === "number" && !Number.isFinite(v) ? `BAD:${v}` : v)));
const line = session.lineFor(car);
const i = session.model.index(car.s);
console.log("elat", (car.x - line.path.px[i]) * session.model.nx[i] + (car.z - line.path.pz[i]) * session.model.nz[i]);
console.log("tracker direct", JSON.stringify(ai.tracker.command(obs.ego, session.model, line.path, dt)));
