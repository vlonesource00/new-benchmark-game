// Re-bake the global line using the MEASURED plant capability curves instead of
// the analytic tyre law. Writes to a separate artifact so A0 (analytic, 82.055 s)
// and A (measured) can be compared without destroying the current bake.
//
//   node tools/bake-measured.mjs

import { readdirSync, writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Track } from '../src/sim/track.js';
import { carSpecFor } from '../src/sim/car-specs.js';
import { buildTrackModel } from '../src/tracks/track-model.js';
import { createEnvelope } from '../src/ai/global/envelope.js';
import { optimizeLine } from '../src/ai/global/line-optimizer.js';
import { RaceLine } from '../src/ai/race-line.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const spec = carSpecFor(arg('class', 'gt'));
const fuelKg = 20;
const mass = spec.mass + fuelKg;
const G = 9.81;
const RHO = 1.225;
const id = JSON.parse(readFileSync(join(root, 'artifacts', 'plant-identification-v2.json'), 'utf8'));

const cdA = spec.area * spec.cd;
const clA = spec.area * spec.cl;
const dragAccel = (v) => (0.5 * RHO * v * v * cdA) / mass;
const rollAccel = (v) => (0.013 * (mass * G + 0.5 * RHO * v * v * clA) * Math.tanh(v * 2)) / mass;
const ENGINE_BRAKE = 0.33;

const curves = {
  latMax: id.tests.capability.map((c) => [c.v, c.latMax]),
  driveForce: id.tests.drive.bins.map((b) => [b.v, mass * (b.value + dragAccel(b.v) + rollAccel(b.v) + ENGINE_BRAKE)]),
  brakeForce: id.tests.brake.bins.map((b) => [b.v, mass * b.value]),
};

const envelope = createEnvelope(spec, { fuelKg, wing: 6, curves });
console.log('[A] measured envelope:');
for (const v of [10, 20, 30, 40, 50, 60]) {
  console.log(`    v=${v}  latMax=${envelope.latMax(v).toFixed(2)}  driveF=${(envelope.driveForce(v) / 1000).toFixed(2)} kN  brakeF=${(envelope.brakeForce(v) / 1000).toFixed(2)} kN  vMax=${envelope.vMax.toFixed(1)}`);
}

const trackId = arg('track', 'harbor-ring');
const track = new Track(trackId === 'harbor-ring' ? 'harbor-ring' : null);
const widths = arg('widths', '96,48,24,12').split(',').map(Number);
const overlap = Number(arg('overlap', 2));
const searchModel = buildTrackModel(track, { spacing: Number(arg('searchSpacing', 2.0)) });
const t0 = Date.now();
const result = optimizeLine(searchModel, envelope, {
  seed: Number(arg('seed', 20260916)),
  widths, overlap,
  seedLabels: arg('seeds', 'centre,inside-late').split(','),
  outerIterations: Number(arg('outer', 3)),
  onProgress: (p) => console.log(`[A]   ${p.seed ?? '-'} ${p.stage} ${p.outer ?? ''}: ${p.time.toFixed(3)} s`),
});
console.log(`[A] search best ${result.time.toFixed(3)} s (${((Date.now() - t0) / 1000).toFixed(1)} s elapsed)`);

const denseModel = buildTrackModel(track, { spacing: Number(arg('finalSpacing', 0.5)) });
const denseLine = new RaceLine(denseModel, envelope, { widths: result.widths, overlap: result.overlap, coeffs: result.coeffs, iterations: 14 });

const meta = {
  track: trackId,
  classId: spec.key,
  variant: 'A-measured',
  widths: result.widths,
  overlap: result.overlap,
  coeffs: Array.from(result.coeffs),
  theoreticalTime: Number(denseLine.time.toFixed(4)),
  searchTime: Number(result.time.toFixed(4)),
  pathLength: Number(denseLine.path.length.toFixed(3)),
  generatedAt: new Date().toISOString(),
  curves: { latMax: curves.latMax, driveForce: curves.driveForce.map((p) => [p[0], +p[1].toFixed(0)]), brakeForce: curves.brakeForce.map((p) => [p[0], +p[1].toFixed(0)]) },
};

const linesDir = join(root, 'src', 'tracks', 'lines');
mkdirSync(linesDir, { recursive: true });
writeFileSync(join(linesDir, `${trackId}-${spec.key}-measured.js`), `// Generated by tools/bake-measured.mjs. Do not edit by hand.\nexport const LINE = ${JSON.stringify(meta)};\n`);
mkdirSync(join(root, 'artifacts'), { recursive: true });
writeFileSync(join(root, 'artifacts', `${trackId}-${spec.key}-measured.json`), JSON.stringify({ ...meta, stationQ: Array.from(denseLine.q) }));

const files = readdirSync(linesDir).filter((f) => f.endsWith('.js') && !['index.js', 'generated.js'].includes(f));
const imports = files.map((f, i) => `import { LINE as line${i} } from './${f}';`).join('\n');
const entries = files.map((f, i) => `  '${f.replace(/\.js$/, '')}': line${i},`).join('\n');
writeFileSync(join(linesDir, 'generated.js'), `// Generated by tools/bake-line.mjs.\n${imports}\nexport const generatedLines = {\n${entries}\n};\n`);

console.log(`[A] dense theoretical lap ${denseLine.time.toFixed(3)} s  path ${denseLine.path.length.toFixed(2)} m`);
console.log(`[A] peak |q| ${Math.max(...Array.from(denseLine.q, Math.abs)).toFixed(2)} m   wrote artifacts/${trackId}-${spec.key}-measured.json`);
