// Bake a DeepSeek global race line for a track/class pair.
//
//   node tools/bake-line.mjs --track harbor-ring --class gt
//
// The artifact stores the smooth multi-scale bump coefficients, which are
// resolution independent: the same line evaluates identically at any station
// density. Writes src/tracks/lines/<track>-<class>.js, a JSON copy under
// artifacts/, and refreshes the generated index.

import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Track } from '../src/sim/track.js';
import { carSpecFor } from '../src/sim/car-specs.js';
import { buildTrackModel } from '../src/tracks/track-model.js';
import { createEnvelope } from '../src/ai/global/envelope.js';
import { optimizeLine } from '../src/ai/global/line-optimizer.js';
import { RaceLine } from '../src/ai/race-line.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const trackId = arg('track', 'harbor-ring');
const classId = arg('class', 'gt');
const seed = Number(arg('seed', 20260916));
const searchSpacing = Number(arg('searchSpacing', 2.0));
const finalSpacing = Number(arg('finalSpacing', 0.5));
const outerIterations = Number(arg('outer', 3));
const widths = arg('widths', '96,48,24,12').split(',').map(Number);
const overlap = Number(arg('overlap', 2));
const seedLabels = arg('seeds', 'centre,inside-late').split(',');

const t0 = Date.now();
const track = new Track(trackId === 'harbor-ring' ? 'harbor-ring' : null);
const spec = carSpecFor(classId);
const searchModel = buildTrackModel(track, { spacing: searchSpacing });
const envelope = createEnvelope(spec, { fuelKg: 20, wing: 6 });

console.log(`[bake] ${trackId}/${spec.key}: search model ${searchModel.n} stations`);

const result = optimizeLine(searchModel, envelope, {
  seed,
  widths,
  overlap,
  seedLabels,
  outerIterations,
  onProgress: (p) => console.log(`[bake]   ${p.seed ?? '-'} ${p.stage} ${p.outer ?? ''}: ${p.time.toFixed(3)} s`),
});
console.log(`[bake] search best ${result.time.toFixed(3)} s  (${((Date.now() - t0) / 1000).toFixed(1)} s elapsed)`);

// Re-evaluate the same smooth line on the dense model for the record.
const denseModel = buildTrackModel(track, { spacing: finalSpacing });
const denseLine = new RaceLine(denseModel, envelope, { widths: result.widths, overlap: result.overlap, coeffs: result.coeffs, iterations: 14 });
const time = denseLine.time;

const meta = {
  track: trackId,
  classId: spec.key,
  widths: result.widths,
  overlap: result.overlap,
  coeffs: Array.from(result.coeffs),
  theoreticalTime: Number(time.toFixed(4)),
  searchTime: Number(result.time.toFixed(4)),
  pathLength: Number(denseLine.path.length.toFixed(3)),
  seed,
  generatedAt: new Date().toISOString(),
  envelope: { mass: envelope.mass, cl: envelope.cl, cd: envelope.cd, vMax: Number(envelope.vMax.toFixed(2)) },
};

const moduleSrc = `// Generated by tools/bake-line.mjs. Do not edit by hand.\nexport const LINE = ${JSON.stringify(meta)};\n`;
const linesDir = join(root, 'src', 'tracks', 'lines');
mkdirSync(linesDir, { recursive: true });
writeFileSync(join(linesDir, `${trackId}-${spec.key}.js`), moduleSrc);

mkdirSync(join(root, 'artifacts'), { recursive: true });
writeFileSync(join(root, 'artifacts', `${trackId}-${spec.key}.json`), JSON.stringify({ ...meta, stationQ: Array.from(denseLine.q) }));

const files = readdirSync(linesDir).filter((f) => f.endsWith('.js') && !['index.js', 'generated.js'].includes(f));
const imports = files.map((f, i) => `import { LINE as line${i} } from './${f}';`).join('\n');
const entries = files.map((f, i) => `  '${f.replace(/\.js$/, '')}': line${i},`).join('\n');
writeFileSync(join(linesDir, 'generated.js'), `// Generated by tools/bake-line.mjs.\n${imports}\nexport const generatedLines = {\n${entries}\n};\n`);

console.log(`[bake] dense theoretical lap ${time.toFixed(3)} s  path ${denseLine.path.length.toFixed(2)} m`);
console.log(`[bake] wrote src/tracks/lines/${trackId}-${spec.key}.js and artifacts/${trackId}-${spec.key}.json`);
