import { Track } from "../src/sim/track.js";
import { buildTrackModel } from "../src/tracks/track-model.js";
import { createEnvelope } from "../src/ai/global/envelope.js";
import { CAR_CLASSES } from "../src/sim/car-specs.js";
import { LINE } from "../src/tracks/lines/harbor-ring-gt.js";
import { makeBasis, expandBumps } from "../src/ai/global/line-optimizer.js";
import { buildPath } from "../src/ai/global/path-geometry.js";
import { speedProfile } from "../src/ai/global/speed-profile.js";
console.log("meta", { widths: LINE.widths, count: LINE.coeffs.length, time: LINE.theoreticalTime, search: LINE.searchTime });
const nan = LINE.coeffs.filter((c) => !Number.isFinite(c)).length;
console.log("non-finite coeffs:", nan);
const track = new Track("harbor-ring");
const model = buildTrackModel(track, { spacing: 0.5 });
const basis = makeBasis(model, { widths: LINE.widths });
console.log("basis count", basis.count, "vs coeffs", LINE.coeffs.length);
const q = expandBumps(model, basis, Float64Array.from(LINE.coeffs));
let bad = 0; for (const v of q) if (!Number.isFinite(v)) bad++;
console.log("non-finite q:", bad, "max|q|", Math.max(...Array.from(q, Math.abs)).toFixed(2));
const path = buildPath(model, q);
let badK = 0; for (const k of path.kappa) if (!Number.isFinite(k)) badK++;
console.log("non-finite kappa:", badK);
const profile = speedProfile(path, CAR_CLASSES ? createEnvelope(CAR_CLASSES.gt, {}) : null, { iterations: 14 });
console.log("dense time", profile.time);
