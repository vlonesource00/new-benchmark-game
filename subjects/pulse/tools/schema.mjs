import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { observationProfile } from '../src/observations.mjs';
import { HOME, versions } from './versions.mjs';
const out = resolve(HOME, 'artifacts');
const v2 = process.argv.includes('--v2'), { schema: SCHEMA } = observationProfile(v2 ? 'pulse-observation-v2' : 'pulse-observation-v1');
mkdirSync(out, { recursive: true });
writeFileSync(resolve(out, v2 ? 'schema-v2.json' : 'schema.json'), JSON.stringify(SCHEMA, null, 2));
writeFileSync(resolve(out, v2 ? 'versions-v2.json' : 'versions.json'), JSON.stringify(versions(SCHEMA), null, 2));
console.log(JSON.stringify({ size: SCHEMA.size, groups: SCHEMA.groups, versions: versions(SCHEMA) }));
