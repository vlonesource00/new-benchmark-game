// Ghost Forge: iterative practice laps with the exact plant. Each lap is
// driven by the PHANTOM planner against the current ghost; a faster valid lap
// becomes the new ghost, and each apex's speed allowance is raised where the
// car survived using it and lowered where the car left the road.
import fs from 'node:fs';
import { Track } from '../../../host/astra/src/sim/track.js';
import { Session } from '../../../host/astra/src/sim/session.js';
import { GhostRecorder } from '../src/ghost.js';
import { loadGhost } from '../src/ghost-store.js';
import { PhantomDriver } from '../src/phantom-driver.js';

const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, '').split('=')));
const ITER = Number(args.iter ?? 6), K = Number(args.K ?? 64), HZ = Number(args.hz ?? 20), H = Number(args.h ?? 2.4);
const STEP = Number(args.step ?? 0.6);
const out = new URL('../src/ghost-data.js', import.meta.url);
const track = new Track('harbor-ring');

async function lap(ghost, delta) {
  const session = new Session(track, { classId: 'gt' });
  session.mode = 'practice'; session.field = 1; session.autopilot = true; session.start({ freshTrack: true });
  session.phase = 'racing'; session.countdown = 0;
  const car = session.player, L = track.length;
  const run = 180, u = L - run;
  car.place(track, ghost.origin + u, ghost.lateral(u), Math.max(20, ghost.speed(u)));
  for (const w of car.wheels) { w.tyre.core = 80; w.tyre.surface = 86; }
  car.race.progress = -run; car.race.previousS = car.s;
  const driver = new PhantomDriver({ track, ghost, planHz: HZ, options: { K, horizon: H } });
  session.drivers[0] = driver;
  const rec = new GhostRecorder(L, ghost.n, ghost.origin);
  const off = new Uint8Array(ghost.n), vmin = new Float32Array(ghost.n).fill(1e9);
  let started = false;
  for (let i = 0; i < 120 * 130; i++) {
    session.step(1 / 120, {});
    if (!started && car.race.progress >= 0) { started = true; rec.begin(session.time); }
    if (started) {
      const uu = ghost.lapDistance(car.s), b = Math.floor(uu / ghost.ds) % ghost.n;
      rec.push(session.time, uu, car);
      if (Math.abs(car.lateral) > track.halfWidth) off[b] = 1;
      vmin[b] = Math.min(vmin[b], car.speed);
    }
    if (car.race.lap >= 2) break;
  }
  const r = car.race;
  const cores = car.wheels.map((w) => w.tyre.core.toFixed(0)).join('/');
  return { time: r.lastLap, valid: r.valid && r.lastLap !== null, off, vmin, rec, cores, offtrack: r.offtrack };
}

let ghost = await loadGhost(track, new (await import('../../../host/astra/src/sim/vehicle.js')).Vehicle(0, 'x', '#000', 'gt'));
const car0 = new (await import('../../../host/astra/src/sim/vehicle.js')).Vehicle(0, 'x', '#000', 'gt');
console.log(`start ghost ${ghost.lapTime.toFixed(3)} apexes ${ghost.apexes.length}`);
for (let it = 1; it <= ITER; it++) {
  const t0 = Date.now();
  const res = await lap(ghost);
  const wall = ((Date.now() - t0) / 1000).toFixed(0);
  // Allowance update per apex.
  const n = ghost.n, before = Math.round(70 / ghost.ds), after = Math.round(30 / ghost.ds);
  const notes = [];
  for (const a of ghost.apexes) {
    let wentOff = false, vm = 1e9;
    for (let k = -before; k <= after; k++) { const b = (a + k + n) % n; if (res.off[b]) wentOff = true; vm = Math.min(vm, res.vmin[b]); }
    const cap = ghost.v[a] + ghost.delta[a];
    if (wentOff) ghost.delta[a] -= 1.2;
    else if (vm > cap - 1.0) ghost.delta[a] += STEP;
    notes.push(`${a}:${ghost.v[a].toFixed(1)}${ghost.delta[a] >= 0 ? '+' : ''}${ghost.delta[a].toFixed(1)}${wentOff ? '!' : ''}`);
  }
  let adopted = false;
  if (res.valid && res.time < ghost.lapTime) {
    const next = res.rec.finish(res.time, null);
    // Carry allowances to the new ghost's apexes from the nearest old apex.
    const old = ghost; next.calibrate(track, car0); next.findApexes();
    for (const a of next.apexes) {
      let bestD = Infinity, d0 = 0;
      for (const b of old.apexes) { const d = Math.min(Math.abs(a - b), n - Math.abs(a - b)); if (d < bestD) { bestD = d; d0 = old.delta[b]; } }
      next.delta[a] = bestD < 40 / next.ds ? Math.min(d0, 1.0) : 0.3;
    }
    next.buildEnvelope();
    ghost = next; adopted = true;
    fs.writeFileSync(out, `// Generated by tools/forge.mjs. Ghost tape of the exact plant on Harbor Ring.\nexport const GHOST = ${JSON.stringify(ghost.toJSON())};\n`);
  } else {
    ghost.buildEnvelope();
  }
  console.log(`it ${it} lap ${res.time?.toFixed(3)} valid ${res.valid} off ${res.offtrack.toFixed(2)}s cores ${res.cores} ${adopted ? 'ADOPTED' : ''} wall ${wall}s`);
  console.log('   ' + notes.join(' '));
}
